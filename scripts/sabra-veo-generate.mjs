import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { loadAssetRegistryFromFile } from "../dist/assets/loader.js";
import { VeoVideoProvider } from "../dist/providers/veo-provider.js";
import { BunnyStorageProvider } from "../dist/storage/bunny-storage-provider.js";

async function loadEnv(path = ".env") {
  const text = await readFile(path, "utf8");
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const index = line.indexOf("=");
    if (index < 1) continue;
    const key = line.slice(0, index).trim();
    let value = line.slice(index + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
    if (!(key in process.env)) process.env[key] = value;
  }
}

function required(name) {
  const value = process.env[name]?.trim();
  if (!value) throw new Error(`Missing ${name} in .env`);
  return value;
}

await loadEnv();
const apiKey = required("GEMINI_API_KEY");
const storageHost = process.env.BUNNY_STORAGE_HOST?.trim();
const storage = new BunnyStorageProvider({
  storageZone: required("BUNNY_STORAGE_ZONE"),
  accessKey: required("BUNNY_STORAGE_ACCESS_KEY"),
  cdnBaseUrl: required("BUNNY_CDN_BASE_URL"),
  ...(storageHost ? { storageHost } : {}),
});

const registry = await loadAssetRegistryFromFile("data/worlds/sabra-world/sabra-assets.canon.json");
const roles = ["FACE_IDENTITY", "BODY_IDENTITY", "COSTUME", "EXPRESSION", "PROPORTIONS"];
const assets = registry.resolveReferences({ worldId: "sabra-world", characterId: "sabra", roles, includeSupporting: true, maxPerRole: 2 });

const shot = {
  id: "shot-1",
  sceneId: "sabra-pilot-01",
  kind: "character",
  durationSeconds: 8,
  characters: ["sabra"],
  action: "Sabra stands naturally in her outdoor environment, notices the camera, and gives a subtle confident smile.",
  emotionalIntent: "warm, natural, confident",
  eyeContactTarget: "camera",
  status: "generating",
};

const model = process.env.VEO_MODEL || "veo-3.1-generate-preview";
const provider = new VeoVideoProvider({ apiKey, model });
const prompt = `${shot.action} Emotional intent: ${shot.emotionalIntent}. Maintain Sabra's exact facial identity, body proportions, costume, and natural appearance from the supplied CANON references. Realistic natural movement, restrained expression, stable anatomy, stable clothing details. No redesign, no age change, no facial drift, no costume substitution.`;

console.log("REAL VEO GENERATION — THIS REQUEST MAY INCUR GEMINI API CHARGES");
console.log(`MODEL ${model}`);
console.log("SHOT 8s | 16:9 | 720p | 1 sample");

const result = await provider.generate({
  shot,
  prompt,
  modelTier: "premium",
  referenceAssetIds: assets.map((asset) => asset.id),
  referenceAssets: assets,
});

console.log("SABRA VEO GENERATION PASS");
console.log(`TEMP VIDEO ${result.assetId}`);
console.log("PRESERVING VIDEO IN BUNNY STORAGE...");

const sourceResponse = await fetch(result.assetId, { headers: { "x-goog-api-key": apiKey } });
if (!sourceResponse.ok) throw new Error(`Gemini video download failed (${sourceResponse.status} ${sourceResponse.statusText})`);
const videoBytes = new Uint8Array(await sourceResponse.arrayBuffer());
if (videoBytes.byteLength === 0) throw new Error("Gemini returned an empty video file");
const contentType = sourceResponse.headers.get("content-type")?.split(";")[0] || "video/mp4";
const sha256 = createHash("sha256").update(videoBytes).digest("hex");
const generatedAt = new Date();
const stamp = generatedAt.toISOString().replace(/[:.]/g, "-");
const storageKey = `worlds/sabra-world/characters/sabra/generated/${shot.sceneId}/${shot.id}/${stamp}-${sha256.slice(0, 12)}.mp4`;
const stored = await storage.upload({ key: storageKey, body: videoBytes, contentType });

const verify = await fetch(stored.uri, { cache: "no-store" });
if (!verify.ok) throw new Error(`Bunny CDN verification failed (${verify.status} ${verify.statusText})`);
const verifiedBytes = new Uint8Array(await verify.arrayBuffer());
const verifiedSha256 = createHash("sha256").update(verifiedBytes).digest("hex");
if (verifiedBytes.byteLength !== videoBytes.byteLength || verifiedSha256 !== sha256) {
  throw new Error("Bunny CDN verification failed: stored video differs from Gemini output");
}

const assetRecord = {
  id: `sabra-${shot.sceneId}-${shot.id}-${sha256.slice(0, 12)}`,
  worldId: "sabra-world",
  characterId: "sabra",
  kind: "video",
  status: "CANDIDATE",
  version: "1",
  uri: stored.uri,
  sha256,
  tags: ["generated", "veo", "pilot", shot.sceneId, shot.id],
  notes: `Generated by ${result.provider}/${result.model}; ${result.durationSeconds}s; source preserved automatically from Gemini.`,
  generation: {
    provider: result.provider,
    model: result.model,
    durationSeconds: result.durationSeconds,
    generatedAt: generatedAt.toISOString(),
    sceneId: shot.sceneId,
    shotId: shot.id,
    prompt,
    referenceAssetIds: assets.map((asset) => asset.id),
  },
};

await mkdir("data/worlds/sabra-world/generated", { recursive: true });
const recordPath = `data/worlds/sabra-world/generated/${assetRecord.id}.json`;
await writeFile(recordPath, `${JSON.stringify(assetRecord, null, 2)}\n`, "utf8");

console.log("BUNNY PRESERVE PASS");
console.log(`VIDEO ${stored.uri}`);
console.log(`SIZE ${stored.sizeBytes} bytes`);
console.log(`SHA256 ${sha256}`);
console.log(`ASSET RECORD ${recordPath}`);
console.log("STATUS CANDIDATE — review before promotion to CANON/APPROVED production output");
